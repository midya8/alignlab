"""Rebuild complete original-data fixture, witnesses and browser data deterministically.

Run with `python scripts/regenerate_frontier.py` from any working directory.
Binary gzip headers fix mtime=0; cross-runtime exp/log differences can change bytes.
"""
import gzip
import json
import pathlib
import sys
root = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root))
from alignlab.frontier_fixtures import reproduce_original
from alignlab.frontier_witnesses import controls, witnesses
fixture = reproduce_original()
serialize = lambda v: json.dumps(v, sort_keys=True, allow_nan=False, separators=(',', ':')) + '\n'
folder = root / 'alignlab' / 'frontier_data'
folder.mkdir(exist_ok=True)
for name, value in [('frozen', fixture), ('witnesses', witnesses(fixture))]:
    (folder / ({'frozen':'3-frozen','witnesses':'4-witnesses'}[name] + '.json.gz')).write_bytes(gzip.compress(serialize(value).encode(), mtime=0))
# All original data and trajectory metrics are retained; duplicate native audits
# are omitted because the browser computes its own audits independently.
data = dict(fixture)
data['runs'] = {name: dict(run, trajectory=[{k: v for k, v in row.items() if k != 'audit'} for row in run['trajectory']]) for name, run in fixture['runs'].items()}
data['controls'] = controls()
(root / 'docs' / '2-data.js').write_text('/* Complete original fixture and trajectories; generated by scripts/regenerate_frontier.py. */\nwindow.ALIGN_DATA=' + serialize(data).rstrip() + ';\n')
print('120 response vectors; 800/150/800 pairs; five full 201-state trajectories; 35 complete witnesses; browser data regenerated')
